def test_vasp4_poscar_is_rejected(tmp_path, capsys):
    p = tmp_path / "old.vasp"
    lines = (DEMO / "structures" / "NaCl.vasp").read_text().splitlines(keepends=True)
    p.write_text("".join(lines[:5] + lines[6:]))                 # drop the species line
    rc = mjf.main(_args(tmp_path / "runs", *LIBRARY, structures=str(p)))
    assert rc == 1
    assert "VASP 4 format" in capsys.readouterr().err


def test_existing_folders_skipped_or_overwritten(tmp_path):
    out = tmp_path / "runs"
    assert mjf.main(_args(out, *LIBRARY)) == 0
    (out / "Si" / "OUTCAR").write_text("result")                 # pretend Si already ran
    (out / "Si" / "INCAR").write_text("ENCUT = 1\n")
    assert mjf.main(_args(out, *LIBRARY)) == 0                   # skipped: untouched
    assert (out / "Si" / "INCAR").read_text() == "ENCUT = 1\n"
    assert "skip (exists)" in (out / "manifest.csv").read_text()
    assert mjf.main(_args(out, *LIBRARY, "--overwrite")) == 0    # inputs rewritten, outputs kept
    assert get_tag((out / "Si" / "INCAR").read_text(), "ENCUT") == "450"
    assert (out / "Si" / "OUTCAR").read_text() == "result"


def test_kpoints_or_kspacing(tmp_path, capsys):
    base = [str(DEMO / "structures" / "Si.vasp"), "--out", str(tmp_path / "runs"),
            "--incar", str(DEMO / "INCAR"), "--potcar-dir", str(DEMO / "fake_potcar_library"),
            "--job-template", str(TEMPLATES / "vasp_single_point.sh")]
    assert mjf.main(base) == 1
    assert "KSPACING" in capsys.readouterr().err
    assert mjf.main(base + ["--set", "KSPACING=0.25"]) == 0
    assert not (tmp_path / "runs" / "Si" / "KPOINTS").exists()


def test_duplicate_names_rejected(tmp_path, capsys):
    for sub in ("a", "b"):
        (tmp_path / sub).mkdir()
        shutil.copy(DEMO / "structures" / "Si.vasp", tmp_path / sub / "Si.vasp")
    rc = mjf.main(_args(tmp_path / "runs", *LIBRARY, structures=str(tmp_path / "*" / "Si.vasp")))
    assert rc == 1
    assert "share the folder name 'Si'" in capsys.readouterr().err


def test_crlf_inputs_become_lf(tmp_path):
    src = tmp_path / "POSCAR_Si"
    src.write_bytes((DEMO / "structures" / "Si.vasp").read_bytes().replace(b"\n", b"\r\n"))
    out = tmp_path / "runs"
    assert mjf.main(_args(out, *LIBRARY, structures=str(src))) == 0
    assert b"\r" not in (out / "Si" / "POSCAR").read_bytes()


