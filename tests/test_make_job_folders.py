"""make_job_folders: one folder per structure, POTCAR order checked, nothing written on error."""
from __future__ import annotations

import csv
import shutil
from pathlib import Path

import pytest

import make_job_folders as mjf
from helpers import DEMO, TEMPLATES
from incar_tags import get_tag


def _args(out: Path, *extra: str, structures: str | None = None) -> list[str]:
    return [structures or str(DEMO / "structures"), "--out", str(out),
            "--incar", str(DEMO / "INCAR"), "--kpoints", str(DEMO / "KPOINTS"),
            "--job-template", str(TEMPLATES / "vasp_relax_autorestart.sh"), *extra]


LIBRARY = ["--potcar-dir", str(DEMO / "fake_potcar_library"), "--potcar-map", "Na=Na_pv"]


def test_demo_campaign(tmp_path, capsys):
    out = tmp_path / "runs"
    rc = mjf.main(_args(out, *LIBRARY, "--set", "ENCUT=520", "--drop", "NCORE",
                        "--job-prefix", "rlx_", "--system-tag"))
    assert rc == 0
    assert sorted(p.name for p in out.iterdir()) == ["Fe_bcc", "NaCl", "Si", "manifest.csv", "submit_all.sh"]
    for name in ("Fe_bcc", "NaCl", "Si"):
        d = out / name
        assert sorted(p.name for p in d.iterdir()) == sorted(mjf.INPUT_FILES)
        for f in d.iterdir():
            assert b"\r\n" not in f.read_bytes(), f
        incar = (d / "INCAR").read_text(encoding="utf-8")
        assert incar.startswith(f"# {name} -- generated by make_job_folders.py")
        assert get_tag(incar, "ENCUT") == "520" and get_tag(incar, "NCORE") is None
        assert get_tag(incar, "SYSTEM") == name
        assert get_tag(incar, "ISMEAR") == "0" and get_tag(incar, "SIGMA") == "0.05"
        assert f"#SBATCH --job-name=rlx_{name}\n" in (d / "job.sh").read_text(encoding="utf-8")
    assert mjf.potcar_titels((out / "NaCl" / "POTCAR").read_text()) == ["Na_pv", "Cl"]
    assert (out / "Si" / "POSCAR").read_text() == (DEMO / "structures" / "Si.vasp").read_text()

    rows = list(csv.DictReader((out / "manifest.csv").open(encoding="utf-8")))
    assert [r["folder"] for r in rows] == ["Fe_bcc", "NaCl", "Si"]
    assert rows[1]["potcar"] == "Na_pv Cl" and rows[1]["formula"] == "NaCl"
    assert rows[0]["incar_changes"] == "set ENCUT=520; drop NCORE"
    submit = (out / "submit_all.sh").read_text(encoding="utf-8")
    assert 'for d in "Fe_bcc" "NaCl" "Si"; do' in submit
    assert "wrote 3 folder(s)" in capsys.readouterr().out


def test_dry_run_writes_nothing(tmp_path, capsys):
    out = tmp_path / "runs"
    assert mjf.main(_args(out, *LIBRARY, "--dry-run")) == 0
    assert not out.exists()
    assert "dry run: 3 folder(s) planned" in capsys.readouterr().out


def test_potcar_order_mismatch_fails_loudly(tmp_path, capsys):
    wrong = tmp_path / "POTCAR"                                  # Cl before Na: wrong order
    wrong.write_text((DEMO / "fake_potcar_library" / "Cl" / "POTCAR").read_text()
                     + (DEMO / "fake_potcar_library" / "Na_pv" / "POTCAR").read_text())
    out = tmp_path / "runs"
    rc = mjf.main(_args(out, "--potcar", str(wrong), structures=str(DEMO / "structures" / "NaCl.vasp")))
    assert rc == 1
    assert not out.exists()
    err = capsys.readouterr().err
    assert "POTCAR species ['Cl', 'Na'] do not match the POSCAR species ['Na', 'Cl']" in err


def test_shared_potcar_must_fit_every_structure(tmp_path, capsys):
    si = DEMO / "fake_potcar_library" / "Si" / "POTCAR"
    rc = mjf.main(_args(tmp_path / "runs", "--potcar", str(si)))   # Si POTCAR for Fe, NaCl and Si
    assert rc == 1
    err = capsys.readouterr().err
    assert err.count("do not match") == 2 and "nothing written" in err


