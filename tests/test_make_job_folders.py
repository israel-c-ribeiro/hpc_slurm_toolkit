def test_cif_through_ase(tmp_path):
    ase_build = pytest.importorskip("ase.build")
    from ase.io import write
    cif = tmp_path / "NaCl_conv.cif"
    write(str(cif), ase_build.bulk("NaCl", "rocksalt", a=5.64, cubic=True))
    out = tmp_path / "runs"
    assert mjf.main(_args(out, *LIBRARY, structures=str(cif))) == 0
    lines = (out / "NaCl_conv" / "POSCAR").read_text().splitlines()
    assert lines[0] == "NaCl_conv" and lines[5].split() == ["Na", "Cl"] and lines[6].split() == ["4", "4"]
